CREATE OR REPLACE FUNCTION public.fetch_posts_with_counts()
 RETURNS TABLE(id uuid, title text, content text, curtidas integer, comentarios integer)
 LANGUAGE plpgsql
AS $function$
begin
  return query
  select 
    p.id, 
    p.title, 
    p.content, 
    co.curtidas, 
    cm.comentarios
  from post p
  inner join (
    select id_post, count(*) as curtidas
    from curtidas
    group by id_post
  ) co on co.id_post = p.id
  inner join (
    select id_post, count(*) as comentarios
    from comment_post
    group by id_post
  ) cm on cm.id_post = p.id;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.get_seguidores(user_id text)
 RETURNS TABLE(id_user text, name character varying, username text)
 LANGUAGE plpgsql
AS $function$
BEGIN
  RETURN QUERY
  SELECT u.id_user, u.name, u.username
  FROM usuarios u
  JOIN seguidores s ON u.id_user = s.pessoa_seguidora_id
  WHERE s.pessoa_seguida_id = user_id;
END;
$function$
;

