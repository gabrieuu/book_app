create or replace view "public"."list_chats_view" as  SELECT p.chat_id,
    c.data_criacao,
    u.name,
    u.username,
    u.id_user,
    m.content,
    m.visualizado,
    m.user_id AS id_do_usuario_que_enviou_ultima_msg
   FROM (((chat_participantes p
     JOIN chat c ON (((p.chat_id = c.id) AND (c."isGrupo" = false))))
     JOIN usuarios u ON ((p.id_user = u.id_user)))
     JOIN mensagens m ON ((m.chat_id = c.id)))
  ORDER BY m.data_enviada DESC;


create or replace view "public"."postagens" as  SELECT p.id,
    p.content,
    p.book_id,
    p.autor_id,
    co.curtidas,
    cm.comentarios
   FROM ((post p
     LEFT JOIN ( SELECT curtidas.id_post,
            count(*) AS curtidas
           FROM curtidas
          GROUP BY curtidas.id_post) co ON ((co.id_post = p.id)))
     LEFT JOIN ( SELECT comment_post.id_post,
            count(*) AS comentarios
           FROM comment_post
          GROUP BY comment_post.id_post) cm ON ((cm.id_post = p.id)));


create or replace view "public"."seguidores_view" as  SELECT u.name,
    u.id_user,
    u.password,
    u.email,
    u.username,
    u.passou_introducao
   FROM (usuarios u
     JOIN seguidores s ON ((u.id_user = s.pessoa_seguidora_id)))
  WHERE (s.pessoa_seguida_id = 'user_id'::text);


